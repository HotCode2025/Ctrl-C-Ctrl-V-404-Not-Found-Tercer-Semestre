package test;

public class AutoboxingUnboxing {
    public static void main(String[] args) {
        
        int enteroPrim = 10;
        System.out.println("enteroPrim = " + enteroPrim);
        Integer entero = 10;
        System.out.println("entero = " + entero);

        int entero2 = entero;
        System.out.println("entero2 = " + entero2);
   
    }
}
